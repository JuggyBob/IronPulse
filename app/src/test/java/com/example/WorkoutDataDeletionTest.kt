/**
 * Data integrity regressions:
 * 1) Deleting a workout session must delete every set logged in that session.
 * 2) "Delete App Data" must wipe every user table but keep the exercise library (including
 *    exercises generated by the AI parser).
 */
@RunWith(RobolectricTestRunner::class)
@Config(sdk = [36])
class WorkoutDataDeletionTest {

    private lateinit var db: AppDatabase
    private lateinit var repository: FitnessRepository

    private val workoutDao: WorkoutDao get() = db.workoutDao()
    private val exerciseDao: ExerciseDao get() = db.exerciseDao()

    @Before
    fun setUp() {
        val context = ApplicationProvider.getApplicationContext<Context>()
        db = Room.inMemoryDatabaseBuilder(context, AppDatabase::class.java)
            .allowMainThreadQueries()
            .build()
        repository = FitnessRepository(
            exerciseDao = db.exerciseDao(),
            workoutDao = db.workoutDao(),
            userProfileDao = db.userProfileDao(),
            savedRoutineDao = db.savedRoutineDao(),
            bodyWeightDao = db.bodyWeightDao(),
            chatDao = db.chatDao(),
        geminiSummaryDao = db.geminiSummaryDao()
        )
    }

    @After
    fun tearDown() {
        db.close()
    }

    @Test
    fun `deleting a session also deletes all of its logged sets`() = runBlocking {
        val sessionA = repository.insertSession(
            WorkoutSession(title = "Push Day", startTime = 1_000L, endTime = 2_000L)
        )
        val sessionB = repository.insertSession(
            WorkoutSession(title = "Pull Day", startTime = 3_000L, endTime = 4_000L)
        )

        repository.insertSets(
            listOf(
                loggedSet(sessionA, "Barbell Bench Press", 1),
                loggedSet(sessionA, "Barbell Bench Press", 2),
                loggedSet(sessionA, "Tricep Pushdown", 1),
                loggedSet(sessionB, "Weighted Pull-up", 1)
            )
        )
        assertEquals(4, repository.getAllCompletedSets().first().size)

        repository.deleteSession(repository.getSessionById(sessionA)!!)

        val remainingSessions = repository.getAllSessions().first()
        val remainingSets = repository.getAllCompletedSets().first()

        assertEquals(listOf("Pull Day"), remainingSessions.map { it.title })
        assertEquals(listOf("Weighted Pull-up"), remainingSets.map { it.exerciseName })
        // No orphaned sets may survive the session deletion
        assertTrue(workoutDao.getSetsForSession(sessionA).first().isEmpty())
    }

    @Test
    fun `deleting one session keeps the exercises of other sessions in the progress analytics`() = runBlocking {
        val keptSession = repository.insertSession(
            WorkoutSession(title = "Leg Day", startTime = 5_000L, endTime = 6_000L)
        )
        val deletedSession = repository.insertSession(
            WorkoutSession(title = "Arm Day", startTime = 7_000L, endTime = 8_000L)
        )
        repository.insertSets(
            listOf(
                loggedSet(keptSession, "Barbell Back Squat", 1),
                loggedSet(deletedSession, "Barbell Curl", 1)
            )
        )

        repository.deleteSession(repository.getSessionById(deletedSession)!!)

        assertEquals(
            listOf("Barbell Back Squat"),
            repository.getDistinctLoggedExerciseNames().first()
        )
    }

    @Test
    fun `delete app data removes every user table but keeps the exercise library`() = runBlocking {
        // Built-in library entry + an exercise "generated" by the AI parser
        val builtIn = exerciseDao.insert(
            Exercise(
                name = "Barbell Bench Press",
                category = "Chest",
                exerciseType = ExerciseType.STANDARD_WEIGHT,
                equipment = "Barbell"
            )
        )
        val aiGenerated = exerciseDao.insert(
            Exercise(
                name = "Pelican Curl",
                category = "Arms",
                exerciseType = ExerciseType.PURE_BODYWEIGHT,
                equipment = "Rings",
                description = "AI registered exercise"
            )
        )

        val sessionId = repository.insertSession(
            WorkoutSession(title = "Full Body", startTime = 10_000L, endTime = 20_000L, notes = "PR day")
        )
        repository.insertSets(listOf(loggedSet(sessionId, "Pelican Curl", 1)))
        repository.saveRoutine(SavedRoutine(name = "My Split", description = "test"))
        repository.insertWeightLog(BodyWeightLog(weightKg = 80.0, timestamp = 11_000L, note = "Fasted"))
        repository.saveUserProfile(
            UserProfile(id = 1, name = "Ivan", currentWeightKg = 80.0, customApiKey = "AIza-secret")
        )
        val chatSession = ChatSession(title = "Coach chat")
        repository.insertChatSession(chatSession)
        repository.insertChatMessage(
            ChatMessageEntity(sessionId = chatSession.id, sender = "USER", text = "How do I muscle up?")
        )

        repository.clearAllUserData()

        // Everything user owned is gone...
        assertTrue(repository.getAllSessions().first().isEmpty())
        assertTrue(repository.getAllCompletedSets().first().isEmpty())
        assertTrue(repository.getDistinctLoggedExerciseNames().first().isEmpty())
        assertTrue(repository.getAllSavedRoutines().first().isEmpty())
        assertTrue(repository.getAllWeightLogs().first().isEmpty())
        assertTrue(repository.getAllChatSessions().first().isEmpty())
        assertNull(repository.getUserProfile().first())
        assertTrue(repository.getAllGeminiSummaries().first().isEmpty())

        // ...while the exercise library survives untouched
        val remainingExercises = exerciseDao.getAllExercises().first()
        assertEquals(2, remainingExercises.size)
        assertEquals(
            setOf("Barbell Bench Press", "Pelican Curl"),
            remainingExercises.map { it.name }.toSet()
        )
        assertEquals(builtIn, remainingExercises.first { it.name == "Barbell Bench Press" }.id)
        assertEquals(aiGenerated, remainingExercises.first { it.name == "Pelican Curl" }.id)
    }

    private fun loggedSet(sessionId: Long, exerciseName: String, setNumber: Int) = LoggedSet(
        sessionId = sessionId,
        exerciseId = 42L,
        exerciseName = exerciseName,
        exerciseType = ExerciseType.PURE_BODYWEIGHT,
        setNumber = setNumber,
        reps = 10,
        timestamp = 1_000L * setNumber
    )
}
